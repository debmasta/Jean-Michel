// Compiles the factory bytebeat formulas with METAL KAP 2's compiler into firmware/src/bb_bank.h: the firmware only holds
// the stack program (flash, no RAM, nothing to parse in the audio path).
//   c++ -std=c++17 tools/bytebeat/gen_bytebeat.cpp -o /tmp/g && /tmp/g > firmware/src/bb_bank.h
#include "Bytebeat.h"
#include <cstdio>
#include <string>
#include <vector>
struct F { const char* name; const char* preset; const char* src; };
// every knob at noon (128) is the original formula; C and D are common to all: C an xor ramp, D a tempo-stepped offset
#define W(f) f   /* C and D are applied by the firmware itself (bb_eval), lighter than in the program */
static const F BANK[] = {
    {"42", "BB 42 MELODY", W("t*(a*21/64&t>>(b>>4)+2)")},
    {"SIERP", "BB SIERPINSKI", W("t*(b>>6)/2&t>>(a>>4)")},
    {"NEURO", "BB NEUROFUNK", W("t*(t>>(a>>5)+1|t>>(b>>4))>>(t>>16)")},
    {"CROWD", "BB CROWD", W("t*(t>>(a>>4)+3&t>>(b>>4)&123&t>>3)")},
    {"STEPS", "BB STEPS", W("t*((T>>(b>>4)+4&3)+1)&(a|t>>8)")},
    {"MELO", "BB MELODIE", W("t*\"CGEGCAFA\"[T>>(a>>4)+3]>>(b>>4)-2")},
    {"METAL", "BB METAL", W("t*(a>>5)+t&t>>7|t*(b>>6)+t&t>>10")},
    {"DUB", "BB DUB", W("(t>>(a>>5)+2|t|t>>(t>>16))*(b*10/128)+(t>>11&7)")},
    {"BREAK", "BB BREAK", W("(T>>10&1?t*(b>>6)+t:t)&(T>>12&3)*85^t>>(a>>4)")},
    {"ARP", "BB ARP", W("t*(1+((a>>5)+1&T>>10))&(96|b)")},
    {"GLTCH", "BB GLITCH", W("t*(t^t+(t>>15|1)^(t-a*10^t)>>(b>>4)+2)")},
    {"STAIR", "BB STAIRS", W("t*((T>>10&(b>>5)+3)+1)>>(a>>5)")},
    {"PWM", "BB PWM", W("(t&255)<(T>>(a>>5)&b*2-1)?255:0")},
    {"HISS", "BB HISS", W("t*t*(t+b-128)>>(a>>4)")},
    {"KICK", "BB KICK LOOP", W("(a*255e3/128/(1+(T&4095))&255)|(T>>10&b)")},
    {"HARM", "BB HARMONICS", W("t*(a&T>>(b>>4)+2)/8")},
};
int main() {
    std::vector<int> ops, args; std::string strs; std::vector<int> off, len; int maxDepth = 0;
    for (const F& f : BANK) {
        auto* p = new m2bb::Prog(m2bb::compile(f.src));
        if (!p->ok) { fprintf(stderr, "%s: %s at %d\n", f.name, p->err, p->errPos); return 1; }
        int d = 0, base = (int)strs.size();
        off.push_back((int)ops.size()); len.push_back(p->n);
        for (int i = 0; i < p->n; ++i) {
            int o = p->op[i], a = p->arg[i];
            if (o == m2bb::IDX) a = ((a & 0xffff) + base) | (a & ~0xffff);
            ops.push_back(o); args.push_back(a);
            d += o <= m2bb::V ? 1 : o <= m2bb::IDX ? 0 : o == m2bb::SEL ? -2 : -1; if (d > maxDepth) maxDepth = d;
        }
        strs.append(p->str, p->nstr);
    }
    puts("/* generated by tools/bytebeat/gen_bytebeat.cpp: do not edit */\n#pragma once");
    printf("#define BB_N %zuu\n#define BB_MAXDEPTH %d\n", sizeof BANK / sizeof *BANK, maxDepth);
    puts("static const uint8_t BB_OP[] = {"); for (int o : ops) printf("%d,", o); puts("};");
    puts("static const int32_t BB_ARG[] = {"); for (int a : args) printf("%d,", a); puts("};");
    puts("static const uint8_t BB_STR[] = {"); for (unsigned char c : strs) printf("%d,", c); puts("0};");
    puts("static const struct { uint16_t off, n; } BB_PROG[BB_N] = {"); for (size_t i = 0; i < off.size(); ++i) printf("{%d,%d},", off[i], len[i]); puts("};");
    printf("static const char *const N_BB[BB_N] = {"); for (const F& f : BANK) printf("\"%s\",", f.name); puts("};");
    puts("#ifdef BB_WITH_SRC\nstatic const char *const BB_SRC[BB_N] = {");
    for (const F& f : BANK) { fputc('"', stdout); for (const char* q = f.src; *q; ++q) { if (*q == '"' || *q == '\\') fputc('\\', stdout); fputc(*q, stdout); } puts("\","); }
    puts("};\n#endif");
    puts("#define BB_PRESET_LIST(X) \\"); int i = 0; for (const F& f : BANK) printf("    X(%d, \"%s\")%s\n", i++, f.preset, i < (int)(sizeof BANK / sizeof *BANK) - 0 ? " \\" : ""); 
    return 0;
}
